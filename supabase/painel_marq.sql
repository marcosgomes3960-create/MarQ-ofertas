-- MarQ Ofertas | Instalação do módulo privado de vendas e comissões
-- Execute no SQL Editor do projeto Supabase: zonclgsfqtylnedxigxd
-- O usuário administrador autorizado é validado por auth.uid() no banco.

create table if not exists public.vendas (
  id bigint generated by default as identity primary key,
  produto_id text null,
  data_venda timestamptz not null default now(),
  valor_venda numeric(12,2) not null default 0 check (valor_venda >= 0),
  comissao numeric(12,2) not null default 0 check (comissao >= 0),
  status text not null default 'estimada'
    check (status in ('estimada','confirmada','paga','cancelada')),
  numero_pedido text null,
  observacoes text null,
  created_at timestamptz not null default now()
);

alter table public.vendas enable row level security;

grant select, insert, update, delete on public.vendas to authenticated;
grant usage, select on sequence public.vendas_id_seq to authenticated;

drop policy if exists "MarQ admin gerencia vendas" on public.vendas;
create policy "MarQ admin gerencia vendas"
on public.vendas
for all
to authenticated
using (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid)
with check (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid);

-- Reforça a política administrativa para leitura dos cliques.
-- A política pública de INSERT de cliques permanece intacta para os visitantes.
drop policy if exists "MarQ admin consulta cliques" on public.cliques;
create policy "MarQ admin consulta cliques"
on public.cliques
for select
to authenticated
using (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid);

-- Produtos continuam públicos para leitura e administráveis somente pela conta autorizada.
drop policy if exists "MarQ admin gerencia produtos" on public.produtos;
create policy "MarQ admin gerencia produtos"
on public.produtos
for all
to authenticated
using (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid)
with check (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid);

