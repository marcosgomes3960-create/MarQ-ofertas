-- Taxas de comissão por produto: tabela separada e privada.
-- Não adicionar a taxa à tabela pública produtos, para nunca expor o dado na vitrine.
create table if not exists public.comissoes_produtos (
  produto_id text primary key,
  taxa_percentual numeric(7,4) not null
    check (taxa_percentual >= 0 and taxa_percentual <= 100),
  updated_at timestamptz not null default now()
);

alter table public.comissoes_produtos
  add column if not exists preco_referencia numeric(12,2) null
    check (preco_referencia is null or preco_referencia >= 0);

alter table public.comissoes_produtos enable row level security;
grant select, insert, update, delete on public.comissoes_produtos to authenticated;
drop policy if exists "MarQ admin gerencia comissoes privadas" on public.comissoes_produtos;
create policy "MarQ admin gerencia comissoes privadas"
on public.comissoes_produtos
for all
to authenticated
using (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid)
with check (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid);

create table if not exists public.vendas (
  id bigint generated by default as identity primary key,
  produto_id text null,
  data_venda timestamptz not null default now(),
  valor_venda numeric(12,2) not null default 0 check (valor_venda >= 0),
  comissao numeric(12,2) not null default 0 check (comissao >= 0),
  status text not null default 'estimada'
    check (status in ('estimada','confirmada','paga','cancelada')),
  numero_pedido text null,
  observacoes text null,
  created_at timestamptz not null default now()
);

-- Campos para identificar a origem da comissão e a taxa usada.
-- A taxa pode ficar nula quando o relatório não a informa.
alter table public.vendas
  add column if not exists tipo_comissao text not null default 'nao_informada'
    check (tipo_comissao in ('direta','indireta','nao_informada')),
  add column if not exists taxa_comissao numeric(7,4) null
    check (taxa_comissao is null or (taxa_comissao >= 0 and taxa_comissao <= 100));

alter table public.vendas enable row level security;

grant select, insert, update, delete on public.vendas to authenticated;
grant usage, select on sequence public.vendas_id_seq to authenticated;

drop policy if exists "MarQ admin gerencia vendas" on public.vendas;
create policy "MarQ admin gerencia vendas"
on public.vendas
for all
to authenticated
using (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid)
with check (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid);

-- Reforça a política administrativa para leitura dos cliques.
-- A política pública de INSERT de cliques permanece intacta para os visitantes.
drop policy if exists "MarQ admin consulta cliques" on public.cliques;
create policy "MarQ admin consulta cliques"
on public.cliques
for select
to authenticated
using (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid);

-- Produtos continuam públicos para leitura e administráveis somente pela conta autorizada.
drop policy if exists "MarQ admin gerencia produtos" on public.produtos;
create policy "MarQ admin gerencia produtos"
on public.produtos
for all
to authenticated
using (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid)
with check (auth.uid() = '89fdb1b1-c59d-4928-8b7d-8e604046d456'::uuid);

